"""Write Part I results: tables (CSV/JSON), figures, and a Markdown report generated from the numbers."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from causeway import eda, schema
from causeway import visualization as viz
from causeway.balance import standardized_mean_difference
from causeway.config import DataPaths
from causeway.experiment import (
    ExperimentResults,
    analyze_experiment,
    assignment_by_strata,
    load_experiment_plan,
)
from causeway.features import COVARIATE_COLUMNS, covariate_matrix
from causeway.pipeline import environment, load_processed


@dataclass
class ExperimentOutputs:
    results: ExperimentResults
    tables: dict[str, pd.DataFrame]
    boundary: dict
    figures: list[Path]
    report_path: Path


def randomization_balance(frame: pd.DataFrame) -> pd.DataFrame:
    covariates = covariate_matrix(frame)
    control = frame["segment"] == schema.CONTROL_ARM
    rows = []
    for arm in schema.ARMS[1:]:
        treated = frame["segment"] == arm
        for column in COVARIATE_COLUMNS:
            rows.append(
                {
                    "comparison": f"{arm} vs {schema.CONTROL_ARM}",
                    "color": viz.ARM_COLORS[arm],
                    "covariate": column,
                    "treated_mean": covariates.loc[treated, column].mean(),
                    "control_mean": covariates.loc[control, column].mean(),
                    "smd": standardized_mean_difference(
                        covariates.loc[treated, column], covariates.loc[control, column]
                    ),
                }
            )
    return pd.DataFrame(rows)


def _fmt_ci(low: float, high: float, scale: float = 1.0, digits: int = 2) -> str:
    return f"[{low * scale:.{digits}f}, {high * scale:.{digits}f}]"


def _num(value: float, spec: str) -> str:
    """Format a number, writing 'undefined' for ratios that cannot be computed (NaN)."""
    return "undefined" if value is None or np.isnan(value) else format(value, spec)


def _fmt_p(p: float | None, floor: float | None = None) -> str:
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "—"
    if floor is not None and p <= floor + 1e-15:
        return f"≤ {floor:.4f}"
    return "< 0.0001" if p < 1e-4 else f"{p:.4f}"


def _markdown_report(outputs: dict, plan: dict, boundary: dict, env: dict) -> str:
    effects: pd.DataFrame = outputs["effects"]
    lift: pd.DataFrame = outputs["relative_lift"]
    binary: pd.DataFrame = outputs["binary"]
    diagnostics: pd.DataFrame = outputs["diagnostics"]
    balance: pd.DataFrame = outputs["balance"]
    strata: pd.DataFrame = outputs["assignment_by_strata"]
    n_perm = plan["inference"]["permutations"]
    floor = 1 / (n_perm + 1)

    def row(contrast: str, outcome: str, estimator: str) -> pd.Series:
        return effects[
            (effects["contrast"] == contrast)
            & (effects["outcome"] == outcome)
            & (effects["estimator"] == estimator)
        ].iloc[0]

    lines = [
        "# Part I — Randomized experiment results",
        "",
        f"Estimand: **{plan['meta']['estimand']}** (two-week window). Generated by `make analysis` from "
        f"`configs/experiment.toml`; Python {env['python']}.",
        "",
        "## Randomization checks",
        "",
        "| Contrast | LR test of covariates predicting arm | Out-of-fold AUC | max \\|SMD\\| |",
        "|---|---|---|---|",
    ]
    for _, d in diagnostics.iterrows():
        if d["contrast"].endswith("control"):
            arm = "Mens E-Mail" if d["contrast"].startswith("mens") else "Womens E-Mail"
            max_smd = balance.loc[balance["comparison"].str.startswith(arm), "smd"].abs().max()
            smd_text = f"{max_smd:.4f}"
        else:
            smd_text = "—"
        lines.append(
            f"| {viz.CONTRAST_LABELS[d['contrast']]} | χ²({d['lr_df']}) = {d['lr_statistic']:.2f}, "
            f"p = {d['lr_p_value']:.3f} | {d['out_of_fold_auc']:.3f} | {smd_text} |"
        )
    strata_p = strata.groupby("stratum")["p_value"].first()
    lines += [
        "",
        "Arm shares are independent of every pre-specified stratum (chi-square p-values: "
        + ", ".join(f"{k} {v:.2f}" for k, v in strata_p.items())
        + "). "
        "These are descriptive checks of the randomization, not tests the analysis depends on.",
        "",
        "## Primary outcome: two-week spend ($ per customer assigned)",
        "",
        "| Contrast | Estimator | Estimate | SE | 95% CI | p | Holm p | Randomization p |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for contrast in ["mens_vs_control", "womens_vs_control", "mens_vs_womens"]:
        for estimator in ["difference_in_means", "lin_adjusted", "bootstrap_percentile", "bootstrap_bca"]:
            r = row(contrast, "spend", estimator)
            p_rand = r.get("p_randomization", np.nan)
            lines.append(
                f"| {viz.CONTRAST_LABELS[contrast]} | {viz.ESTIMATOR_LABELS[estimator]} "
                f"| {r['estimate']:.3f} | {r['se']:.3f} | {_fmt_ci(r['ci_low'], r['ci_high'], digits=3)} "
                f"| {_fmt_p(r.get('p_value'))} | {_fmt_p(r.get('p_holm'))} | {_fmt_p(p_rand, floor)} |"
            )
    lines += [
        "",
        f"Randomization p-values use {n_perm:,} permutations; `≤ {floor:.4f}` means no permutation "
        "produced a difference as large as the observed one. "
        "Holm adjustment covers the two co-primary contrasts.",
        "",
        "## Secondary outcomes",
        "",
        "| Contrast | Outcome | Risk (treated) | Risk (comparison) | Risk difference (pp) "
        "| Newcombe 95% CI (pp) | Risk ratio | 95% CI | Holm p |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for _, b in binary.iterrows():
        holm_p = row(b["contrast"], b["outcome"], "difference_in_means").get("p_holm")
        lines.append(
            f"| {viz.CONTRAST_LABELS[b['contrast']]} | {b['outcome']} | {b['risk_treated']:.4f} | "
            f"{b['risk_control']:.4f} | {b['risk_difference'] * 100:.2f} | "
            f"{_fmt_ci(b['rd_ci_low'], b['rd_ci_high'], 100)} | {_num(b['risk_ratio'], '.2f')} | "
            f"[{_num(b['rr_ci_low'], '.2f')}, {_num(b['rr_ci_high'], '.2f')}] | {_fmt_p(holm_p)} |"
        )
    lines += [
        "",
        "## Relative effects (bootstrap percentile intervals)",
        "",
        "| Contrast | Outcome | Comparison-arm mean | Relative change | 95% CI |",
        "|---|---|---|---|---|",
    ]
    for _, r in lift.iterrows():
        lines.append(
            f"| {viz.CONTRAST_LABELS[r['contrast']]} | {r['outcome']} | {r['control_mean']:.4f} | "
            f"{_num(r['relative_lift'], '+.1%')} | "
            f"[{_num(r['ci_low'], '+.1%')}, {_num(r['ci_high'], '+.1%')}] |"
        )

    lines += ["", "## Interpretation (generated from the estimates above)", ""]
    for contrast in ["mens_vs_control", "womens_vs_control"]:
        r = row(contrast, "spend", "difference_in_means")
        lift_row = lift[(lift["contrast"] == contrast) & (lift["outcome"] == "spend")].iloc[0]
        lines.append(
            f"- **{viz.CONTRAST_LABELS[contrast]}:** assignment changed average two-week spend by "
            f"${r['estimate']:.2f} per customer (95% CI ${r['ci_low']:.2f} to ${r['ci_high']:.2f}; Holm p "
            f"{_fmt_p(r['p_holm'])}), {_num(lift_row['relative_lift'], '+.0%')} relative to the "
            f"No E-Mail mean of ${lift_row['control_mean']:.2f}."
        )
    secondary = row("mens_vs_womens", "spend", "difference_in_means")
    lines += [
        f"- **Mens vs Womens (secondary, unadjusted):** ${secondary['estimate']:.2f} "
        f"(95% CI ${secondary['ci_low']:.2f} to ${secondary['ci_high']:.2f}).",
        "- These are effects of *assignment*. The data record no delivery or opening, so they say nothing "
        "directly about the effect of reading an e-mail.",
        "",
        "## Spend boundary",
        "",
        f"{plan['spend_boundary']['observed_maximum_note']} {boundary['n_at_maximum']} of "
        f"{boundary['n_converters']} purchasers ({boundary['share_at_maximum']:.1%}) spent exactly "
        f"${boundary['maximum']:.2f}.",
        "",
        "| Band | Purchasers | Share of purchasers | Mens | Womens | No E-Mail |",
        "|---|---|---|---|---|---|",
    ]
    for band in boundary["bands"]:
        lines.append(
            f"| {band['band']} | {band['n']} | {band['share_of_converters']:.1%} | {band['n_mens']} | "
            f"{band['n_womens']} | {band['n_control']} |"
        )
    lines += [
        "",
        "Largest distinct values below the maximum: "
        + ", ".join(f"${v:.2f}" for v in boundary["largest_values_below_maximum"])
        + ".",
        "",
        "Most frequent spend values among purchasers: "
        + ", ".join(f"${v['spend']:.2f} (n = {v['n']})" for v in boundary["most_frequent_values"][:5])
        + ".",
        "",
    ]
    return "\n".join(lines)


def run_experiment_report(paths: DataPaths | None = None) -> ExperimentOutputs:
    paths = paths or DataPaths()
    frame = load_processed(paths)
    plan = load_experiment_plan()
    results = analyze_experiment(frame, plan)

    results_dir = paths.root / "reports" / "results" / "experiment"
    figures_dir = paths.root / "reports" / "figures" / "experiment"
    results_dir.mkdir(parents=True, exist_ok=True)

    boundary = eda.spend_boundary(frame, plan["spend_boundary"]["near_boundary_bins"])
    tables = {
        "effects": results.effects,
        "binary": results.binary,
        "relative_lift": results.relative_lift,
        "diagnostics": results.diagnostics,
        "balance": randomization_balance(frame),
        "assignment_by_strata": assignment_by_strata(
            frame, plan["diagnostics"]["strata_for_assignment_check"]
        ),
        "outcome_summary": eda.outcome_summary(frame),
        "covariate_correlations": eda.covariate_correlations(frame),
        "prognostic_correlations": eda.prognostic_correlations(frame),
    }
    for name, table in tables.items():
        table.to_csv(results_dir / f"{name}.csv", index=name.endswith("correlations"))
    results.bootstrap_draws.to_csv(results_dir / "bootstrap_draws.csv", index=False)
    env = environment()
    (results_dir / "summary.json").write_text(
        json.dumps(
            {"plan": plan, "environment": env, "spend_boundary": boundary, **results.summary()},
            indent=2,
            default=float,
        )
        + "\n"
    )

    figures = [
        viz.outcome_levels(frame, figures_dir / "outcome_levels_by_arm.png"),
        viz.spend_among_converters(frame, figures_dir / "spend_among_purchasers.png", boundary["maximum"]),
        viz.love_plot(
            tables["balance"],
            figures_dir / "balance_randomized.png",
            threshold=plan["diagnostics"]["smd_reference"],
        ),
        viz.effect_forest(
            results.effects,
            figures_dir / "itt_effects.png",
            ["difference_in_means", "lin_adjusted", "bootstrap_bca"],
        ),
        viz.bootstrap_distributions(
            results.bootstrap_draws, results.effects, figures_dir / "bootstrap_spend_effects.png"
        ),
    ]
    report_path = results_dir / "experiment_report.md"
    report_path.write_text(_markdown_report(tables, plan, boundary, env))
    return ExperimentOutputs(results, tables, boundary, figures, report_path)
